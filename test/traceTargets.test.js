import test from 'node:test';
import assert from 'node:assert/strict';
import {createBattleState,battleReducer} from '../src/battle/battleState.js';
import {traceTargetAbilities,invalidTraceSelections} from '../src/battle/traceTargets.js';
import {speciesByName} from '../src/battle/reference.js';
const id=name=>speciesByName.get(name.toLowerCase()).internalSpeciesId;
const records=[{identity:'trace',dex:280,ability:'Trace'},{identity:'fire',dex:229,ability:'Flash Fire'},{identity:'bench',dex:143,ability:'Immunity'}];
const initial=(format='Singles')=>({...createBattleState(),rules:{...createBattleState().rules,format},team:records.map(m=>m.identity),opponentSpecies:['Houndoom','Snorlax','Ralts'].map(id),matchup:{player:'trace',opponent:id('Houndoom')}});
const reconcile=s=>battleReducer(s,{type:'reconcileTraceSelections',records});
const observed=(s,slot,ability)=>({...s,opponentObservations:{...s.opponentObservations,[slot]:{moves:[],item:'',ability}}});
const saved=(s,side,slot,context,copiedAbility)=>({...s,matchupConditions:{...s.matchupConditions,[side]:{...s.matchupConditions[side],[slot]:{currentHp:null,status:'none',stages:{attack:2},helpingHand:true,abilityState:{context,copiedAbility,flashFireActivated:true}}}}});
test('Singles uses only the selected opposing Pokémon, respects observations and never auto-selects',()=>{
 let s=initial();assert.deepEqual(traceTargetAbilities(s,'player',records),['Early Bird','Flash Fire']);
 s=observed(s,0,'Flash Fire');assert.deepEqual(traceTargetAbilities(s,'player',records),['Flash Fire']);
 assert.equal(reconcile(s),s);
 s={...s,matchup:{...s.matchup,opponent:id('Snorlax')}};
 assert.deepEqual(traceTargetAbilities(s,'player',records),['Immunity','Thick Fat']);
 assert.deepEqual(traceTargetAbilities(s,'enemy',records),['Trace']);
 s={...s,matchup:{...s.matchup,player:'fire'}};
 assert.deepEqual(traceTargetAbilities(s,'enemy',records),['Flash Fire']);
});
test('Doubles unions both active slots independently of viewed opponent, excludes bench/empty/fainted targets and deduplicates',()=>{
 let s=initial('Doubles');assert.deepEqual(traceTargetAbilities(s,'player',records),['Early Bird','Flash Fire','Immunity','Thick Fat']);
 assert.deepEqual(traceTargetAbilities(s,'enemy',records),['Flash Fire','Trace']);
 s={...s,matchup:{...s.matchup,opponent:id('Snorlax')}};
 assert.deepEqual(traceTargetAbilities(s,'player',records),['Early Bird','Flash Fire','Immunity','Thick Fat']);
 s=observed(observed(s,0,'Flash Fire'),1,'Thick Fat');
 assert.deepEqual(traceTargetAbilities(s,'player',records),['Flash Fire','Thick Fat']);
 s={...s,matchupConditions:{...s.matchupConditions,enemy:{0:{currentHp:0}}}};
 assert.deepEqual(traceTargetAbilities(s,'player',records),['Thick Fat']);
 s={...s,opponentSpecies:[null,id('Snorlax'),id('Ralts')]};
 assert.deepEqual(traceTargetAbilities(s,'player',records),['Thick Fat']);
 const duplicate=[records[0],{...records[1],identity:'fire2'},records[1]];
 s={...s,team:['fire','fire2','trace']};
 assert.deepEqual(traceTargetAbilities(s,'enemy',duplicate),['Flash Fire']);
});
test('ineligible copies clear activation even in unviewed active slots, preserving unrelated conditions',()=>{
 let s=initial('Doubles');s=saved(s,'player',0,'Trace','Flash Fire');
 assert.equal(reconcile(s),s,'legitimate copy retained');
 s={...s,matchup:{...s.matchup,player:'fire'}};
 s=observed(s,0,'Early Bird');
 assert.deepEqual(invalidTraceSelections(s,records),[{side:'player',slot:0}]);
 const before=structuredClone(s),next=reconcile(s);
 assert.deepEqual(s,before,'no mutation');
 assert.deepEqual(next.matchupConditions.player[0].abilityState,{context:'Trace',copiedAbility:null,flashFireActivated:false});
 assert.deepEqual(next.matchupConditions.player[0].stages,{attack:2});
 assert.equal(next.matchupConditions.player[0].helpingHand,true);
 assert.equal(next.matchupSides,s.matchupSides);assert.equal(next.field,s.field);
 assert.equal(reconcile(next),next,'idempotent');
});
test('Singles switching, fainting and opponent-side Trace use actual opposite-side records',()=>{
 let s=saved(initial(),'player',0,'Trace','Flash Fire');
 s={...s,matchup:{...s.matchup,opponent:id('Snorlax')}};
 assert.equal(reconcile(s).matchupConditions.player[0].abilityState.copiedAbility,null);
 s=saved(initial(),'player',0,'Trace','Flash Fire');
 s={...s,matchupConditions:{...s.matchupConditions,enemy:{0:{currentHp:0}}}};
 assert.deepEqual(traceTargetAbilities(s,'player',records),[]);
 assert.equal(reconcile(s).matchupConditions.player[0].abilityState.flashFireActivated,false);
 s={...initial(),matchup:{player:'fire',opponent:id('Ralts')}};
 s=saved(s,'enemy',2,'Synchronize|Trace','Flash Fire');
 assert.equal(reconcile(s),s);
 s={...s,matchup:{...s.matchup,player:'bench'}};
 assert.equal(reconcile(s).matchupConditions.enemy[2].abilityState.copiedAbility,null);
});
test('a target with resolved Trace contributes its effective copied ability without unrelated abilities',()=>{
 let s={...initial(),matchup:{player:'fire',opponent:id('Ralts')}};
 s=saved(s,'enemy',2,'Synchronize|Trace','Flash Fire');
 assert.deepEqual(traceTargetAbilities(s,'player',records),['Flash Fire','Synchronize']);
});
