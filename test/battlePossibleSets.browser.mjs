import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium,webkit} from 'playwright';
import {preview} from 'vite';
import {towerSetById} from '../src/battle/towerSets.js';
const useWebKit=process.argv.includes('--webkit');
const server=await preview({preview:{host:'127.0.0.1',port:useWebKit?5219:5218,strictPort:true}});
const browser=await(useWebKit?webkit.launch({headless:true}):chromium.launch({headless:true,channel:'chrome'}));
const errors=[];
try{
 await mkdir('artifacts/possible-sets',{recursive:true});
 for(const [width,height] of [[320,568],[375,667],[390,844],[430,932],[1440,900]]){
  const touch=width<500,context=await browser.newContext({viewport:{width,height},isMobile:touch,hasTouch:touch,serviceWorkers:'block'});
  const page=await context.newPage();page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message));
  const tap=async el=>touch?el.tap():el.click();
  await page.goto(new URL('/emerald-companion-2/',server.resolvedUrls.local[0]).href);
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();await page.getByRole('button',{name:'Battle',exact:true}).click();
  const region=page.getByRole('region',{name:'Possible Sets',exact:true});
  const list=region.locator('.battle-possible-set-list > button');
  const opponent=page.getByRole('region',{name:'Opponent Team',exact:true});
  const slots=opponent.locator('.battle-compact-slot');
  const matchup=page.getByRole('group',{name:'Opponent matchup Pokémon',exact:true});
  const trainer=opponent.locator('.battle-opponent-trigger');
  const stored=()=>page.evaluate(()=>Object.fromEntries(Object.entries(localStorage)));
  const add=async(slot,name)=>{await tap(slots.nth(slot));const picker=page.getByRole('dialog',{name:'Select opponent Pokémon'});await picker.getByRole('searchbox').fill(name);await tap(picker.getByRole('button',{name:`Select Pokémon ${name}`,exact:true}));};
  const double=async el=>{await page.waitForTimeout(450);if(touch){await tap(el);await tap(el);}else await el.dblclick();await page.waitForTimeout(450);};
  assert.equal(await list.count(),0);
  assert.ok(await region.evaluate(el=>el.parentElement.classList.contains('home-resources')));
  assert.ok((await region.boundingBox()).y>=(await opponent.boundingBox()).y+(await opponent.boundingBox()).height);
  await add(0,'Metagross');assert.equal(await list.count(),0,'team population never selects a set or matchup');
  await tap(slots.nth(0));
  assert.deepEqual(await list.allTextContents(),Array.from({length:8},(_,index)=>`Metagross ${index+1}`));
  const lineupBefore=await opponent.locator('.battle-compact-slots').innerHTML(), matchupBefore=await matchup.innerHTML(), storageBefore=await stored();
  const details=page.getByRole('dialog',{name:'Metagross 2',exact:true});
  await tap(region.getByRole('button',{name:'Metagross 2',exact:true}));await details.waitFor();
  const set=towerSetById('Metagross 2');
  assert.deepEqual(await details.locator('dt').allTextContents(),['Ability','Held item']);
  assert.deepEqual(await details.locator('dd').allTextContents(),[set.possibleAbility,set.item]);
  assert.deepEqual(await details.getByRole('list',{name:'Moves'}).locator('li').allTextContents(),set.moves);
  assert.match(await details.locator('.battle-set-details-heading img').getAttribute('src'),/pokemon\/emerald\/normal\/376.png/);
  await details.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(img=>img.decode())));
  assert.equal(await details.locator('input,select,button').count(),0,'details are informational only');
  assert.equal(await opponent.locator('.battle-compact-slots').innerHTML(),lineupBefore);assert.equal(await matchup.innerHTML(),matchupBefore);assert.deepEqual(await stored(),storageBefore);
  const box=await details.boundingBox();assert.ok(box.x>=0&&box.x+box.width<=width+1&&box.y>=0&&box.y+box.height<=height+1,'compact details fit viewport');
  await page.screenshot({path:`artifacts/possible-sets/${useWebKit?'webkit':'chrome'}-${width}.png`,fullPage:true});
  await details.click({position:{x:2,y:2}});assert.equal(await details.count(),0);
  await tap(region.getByRole('button',{name:'Metagross 2',exact:true}));await page.keyboard.press('Escape');assert.equal(await details.count(),0);
  await tap(region.getByRole('button',{name:'Metagross 2',exact:true}));await page.mouse.click(4,100);assert.equal(await details.count(),0);
  await tap(trainer);const trainers=page.getByRole('dialog',{name:'Select opponent trainer'});
  await trainers.getByRole('searchbox').fill('COOPER');await tap(trainers.getByRole('button',{name:'Select trainer COOPER',exact:true}));
  assert.deepEqual(await list.allTextContents(),['Metagross 1'],'only COOPER’s actual set is eligible');
  await tap(list.first());assert.equal(await page.getByRole('dialog',{name:'Metagross 1',exact:true}).count(),1);await page.keyboard.press('Escape');
  await double(trainer);assert.equal(await list.count(),0,'clearing trainer/team removes stale possible sets');
  await add(0,'Metagross');await tap(slots.nth(0));assert.equal(await list.count(),8);
  await add(1,'Caterpie');await tap(slots.nth(1));
  assert.deepEqual(await list.allTextContents(),['Caterpie 1']);
  await tap(list.first());const caterpie=page.getByRole('dialog',{name:'Caterpie 1',exact:true});
  assert.deepEqual(await caterpie.getByRole('list',{name:'Moves'}).locator('li').allTextContents(),towerSetById('Caterpie 1').moves,'do not invent moves missing from database');
  await tap(slots.nth(0));assert.equal(await caterpie.count(),0);assert.deepEqual(await list.allTextContents(),['Caterpie 1']);
  await tap(slots.nth(0));assert.equal(await list.count(),8);
  await tap(slots.nth(1));assert.equal(await page.getByRole('dialog').count(),0,'changing context never reopens old details');
  await double(slots.nth(1));assert.equal(await list.count(),0);assert.equal(await matchup.locator('img').count(),0);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await context.close();console.log(`PASS ${width}px: selected species only, numbered ordering, exact trainer eligibility, read-only database details, missing moves, popup dismissal, context cleanup and responsive layout.`);
 }
 assert.deepEqual(errors,[]);
}finally{await browser.close();await new Promise(resolve=>server.httpServer.close(resolve));}
