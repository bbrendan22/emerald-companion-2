import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createServer} from 'vite';

const server = await createServer({server:{host:'127.0.0.1',port:5202,strictPort:true}});
await server.listen();
const browser = await chromium.launch({headless:true,channel:'chrome'});
try {
  const page = await browser.newPage({viewport:{width:320,height:568}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const navigate = async () => {
    await page.getByRole('button',{name:'Open navigation',exact:true}).click();
    await page.getByRole('button',{name:'Battle',exact:true}).click();
  };
  const trigger = page.getByRole('button',{name:'Battle Rules',exact:true});
  const popup = page.getByRole('dialog',{name:'Battle Rules',exact:true});
  const round = page.getByLabel('Round',{exact:true});
  await page.goto(server.resolvedUrls.local[0]);
  await navigate();
  assert.equal(await round.inputValue(),'');
  assert.equal(await page.locator('.battle-round-control > span').innerText(),'Round ▾');
  const options = ['', '1','2','3','4','5','6','7','8+'];
  assert.deepEqual(await round.locator('option').allTextContents(), options.map(value => value ? `Round ${value}` : 'All Rounds'));
  const before = await page.locator('.battle-workspace-panel').evaluateAll(panels => panels.map(panel => panel.innerText).join(''));
  const savedRules = await page.evaluate(() => localStorage.getItem('emerald-companion-2.battle-rules.v1'));
  for (const value of options) {
    await round.selectOption(value);
    assert.equal(await round.inputValue(),value);
    assert.equal(await page.locator('.battle-workspace-panel').evaluateAll(panels => panels.map(panel => panel.innerText).join('')),before);
    assert.equal(await page.evaluate(() => localStorage.getItem('emerald-companion-2.battle-rules.v1')),savedRules);
  }
  const trainerButton = page.getByRole('button',{name:'Choose opponent trainer: Select Trainer',exact:true});
  const trainerSearch = page.getByRole('searchbox',{name:'Search Tower trainers'});
  const speciesSearch = page.getByRole('searchbox',{name:'Search opponent Pokémon'});
  const trainerDialog = page.getByRole('dialog',{name:'Select opponent trainer',exact:true});
  const speciesDialog = page.getByRole('dialog',{name:'Select opponent Pokémon',exact:true});
  await round.selectOption('1');
  await trainerButton.click();
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),120);
  await trainerSearch.fill('GILLIAN');
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),1);
  await trainerSearch.fill('BRADY');
  await page.getByRole('button',{name:'Select trainer BRADY',exact:true}).click();
  await page.getByRole('button',{name:'Add Pokémon, Opponent Team, empty slot 1',exact:true}).click();
  await speciesSearch.fill('Sunkern');
  await page.getByRole('button',{name:'Select Pokémon Sunkern',exact:true}).click();
  await page.getByRole('button',{name:'Sunkern, Opponent Team, slot 1',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Sunkern, Opponent Team, slot 1',exact:true}).getAttribute('aria-pressed'),'true');
  await round.selectOption('8+');
  assert.equal(await page.getByText('Possible Sets',{exact:true}).count(),0);
  assert.equal(await page.getByRole('button',{name:'Sunkern, Opponent Team, slot 1',exact:true}).count(),0);
  await trainerButton.click();
  assert.equal(await trainerSearch.inputValue(),'');
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),101);
  await trainerSearch.fill('GILLIAN');
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),1);
  assert.match(await trainerDialog.locator('.battle-opponent-result').innerText(),/Cooltrainer/);
  await page.keyboard.press('Escape');
  // Independent species search must work with no trainer selected.
  await round.selectOption('1');
  await page.getByRole('button',{name:'Add Pokémon, Opponent Team, empty slot 1',exact:true}).click();
  await speciesSearch.fill('Sunkern');
  assert.equal(await page.getByRole('button',{name:'Select Pokémon Sunkern',exact:true}).count(),1);
  await round.selectOption('8+');
  assert.equal(await speciesDialog.count(),0);
  await page.getByRole('button',{name:'Add Pokémon, Opponent Team, empty slot 1',exact:true}).click();
  assert.equal(await speciesSearch.inputValue(),'');
  await speciesSearch.fill('Sunkern');
  assert.equal(await page.getByRole('button',{name:'Select Pokémon Sunkern',exact:true}).count(),0);
  await page.keyboard.press('Escape');
  await round.selectOption('');
  await trainerButton.click();
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),302);
  await page.getByRole('button',{name:'Select trainer BRADY',exact:true}).click();
  await round.selectOption('');
  assert.equal(await page.getByRole('button',{name:/BRADY; double-tap/}).count(),1,'active value must not reset');
  await trigger.click();
  await popup.getByLabel('Level',{exact:true}).selectOption('78');
  assert.equal(await trainerButton.count(),1);
  await trigger.click();
  await trainerButton.click();
  await page.getByRole('button',{name:'Select trainer BRADY',exact:true}).click();
  await trigger.click();
  await popup.getByLabel('Battle Type').selectOption('Doubles');
  assert.equal(await trainerButton.count(),1);
  await popup.getByLabel('Battle Type').selectOption('Singles');
  await round.focus();
  await round.selectOption('8+');
  await trigger.click();
  assert.equal(await popup.getByLabel('Round',{exact:true}).count(),0);
  await popup.getByLabel('Level',{exact:true}).selectOption('78');
  await popup.getByLabel('Battle Type').selectOption('Doubles');
  assert.equal(await round.inputValue(),'8+');
  assert.equal(await page.locator('.battle-rules-summary').innerText(),'Tower · Doubles · Open 78');
  const rect = await popup.boundingBox();
  assert.ok(rect.x >= 0 && rect.x + rect.width <= 320 && rect.y + rect.height <= 568);
  assert.ok(rect.height < 190 && rect.width < 240);
  assert.ok(await round.evaluate(select => getComputedStyle(select).fontSize === '16px' && select.getBoundingClientRect().height >= 36));
  await page.screenshot({path:'/tmp/emerald-battle-round-320.png'});
  await page.reload();
  await navigate();
  assert.equal(await round.inputValue(),'8+');
  await trigger.click();
  assert.equal(await popup.getByLabel('Level',{exact:true}).inputValue(),'78');
  assert.equal(await popup.getByLabel('Battle Type').inputValue(),'Doubles');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await round.focus();
  assert.equal(await popup.count(),0);
  // Restored Doubles uses the same round filter, with no Brain entries.
  await trainerButton.click();
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),100);
  const names=await trainerDialog.locator('.battle-opponent-result strong').allTextContents();
  assert.deepEqual(names,[...names].sort((a,b)=>a.localeCompare(b)));
  await trainerSearch.fill('Anabel');
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),0);
  await round.selectOption('1');
  assert.equal(await trainerDialog.count(),0);
  await trainerButton.click();
  assert.equal(await trainerSearch.inputValue(),'');
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),120);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Add Pokémon, Opponent Team, empty slot 1',exact:true}).click();
  await speciesSearch.fill('Sunkern');
  assert.equal(await page.getByRole('button',{name:'Select Pokémon Sunkern',exact:true}).count(),1);
  await round.selectOption('8+');
  await page.getByRole('button',{name:'Add Pokémon, Opponent Team, empty slot 1',exact:true}).click();
  assert.equal(await speciesSearch.inputValue(),'');
  await speciesSearch.fill('Sunkern');
  assert.equal(await page.getByRole('button',{name:'Select Pokémon Sunkern',exact:true}).count(),0);
  await page.keyboard.press('Escape');
  await round.selectOption('');
  await trainerButton.click();
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),300);
  await trainerSearch.fill('Anabel');
  assert.equal(await trainerDialog.locator('.battle-opponent-result').count(),0);
  await page.keyboard.press('Escape');
  for (const width of [375,390]) {
    await page.setViewportSize({width,height:844});
    const boxes = await page.locator('.battle-rules-heading').evaluate(header => [...header.children].map(child => {
      const r=child.getBoundingClientRect(); return {x:r.x,right:r.right,y:r.y,bottom:r.bottom};
    }));
    assert.ok(boxes[0].right <= boxes[1].x && boxes[1].right <= boxes[2].x);
    assert.ok(boxes.every(box => box.x >= 0 && box.right <= width));
    assert.ok(boxes[1].y < boxes[0].bottom && boxes[2].y < boxes[0].bottom);
    await page.screenshot({path:`/tmp/emerald-battle-round-${width}.png`});
  }
  assert.deepEqual(errors,[]);
  console.log('PASS Singles/Doubles Round: canonical trainer filtering, independent species filtering, opponent/search resets, active-value no-op, All Rounds restoration, persistence, approved header layout.');
} finally {
  await browser.close();
  await server.close();
}
